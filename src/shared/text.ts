// 文字の項目で受け付ける文字。API の検証（schemas.ts）と画面の入力チェックで同じ条件を使うため、zod を使わないここに置く
// （schemas.ts に置くと、画面のコードに zod まで取り込まれるため。profile.ts と同じ理由）。
// 表示名・休止理由・学会名など、1行で全員に表示される項目では、次の文字を受け付けない（見えない名前や見た目の偽装、保存時の 500 を防ぐ）。
// 前後にあるものも取り除かずに拒否するため、trim より先に確かめる（trim は改行・行区切り・BOM も取り除いてしまう）
// - Cc: 改行・NUL などの制御文字（NUL は PostgreSQL の text に保存できない）
// - Cf: ゼロ幅スペースや文字の向きを変える文字などの書式文字
// - Cs: 対になっていないサロゲート（Neon に送る JSON が壊れて 500 になる）
// - Zl / Zp: 行区切り・段落区切り（改行と同じ働きをする）
// 見た目が空白になる普通の文字（ハングルの埋め字 U+3164 など）は分類が文字なので、ここでは防げない
export const PRINTABLE_SINGLE_LINE = /^[^\p{Cc}\p{Cf}\p{Cs}\p{Zl}\p{Zp}]*$/u;

// 複数行の文章（全体連絡の本文、学会の補足・説明・メモ）で受け付ける文字。PRINTABLE_SINGLE_LINE と同じ文字を拒否するが、改行（\n）とタブだけは許す。
// CR（\r）は許さない（ブラウザの入力欄は改行を \n にそろえて渡すため、画面から送る分には困らない）
export const PRINTABLE_MULTI_LINE =
	/^(?:[\n\t]|[^\p{Cc}\p{Cf}\p{Cs}\p{Zl}\p{Zp}])*$/u;
